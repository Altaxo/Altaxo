    [Fact]
    public void TestInverseLangevin_LargeValues_ShouldNotDeviateAtAll()
    {
      for (int i = 5; i < 32; ++i)
      {
        var y = Hyperbolic.InverseLangevin(1 - RMath.Pow(2, -i));
        var expected = RMath.Pow(2, i);
        var bitDeviation = AbsNumberOfLeastBitsDeviating(expected, y);
        Assert.True(bitDeviation == 0);
      }

      for (int i = 5; i < 32; ++i)
      {
        var y = Hyperbolic.InverseLangevin(-1 + RMath.Pow(2, -i));
        var expected = -RMath.Pow(2, i);
        var bitDeviation = AbsNumberOfLeastBitsDeviating(expected, y);
        Assert.True(bitDeviation == 0);
      }
    }

    private static double AbsNumberOfLeastBitsDeviating(double expected, double actual)
    {
      double oneBit = expected - Math.BitDecrement(expected);
      return Math.Abs((expected - actual) / oneBit);
    }



